final GlobalKey<NavigatorState> rootNavigatorKey = GlobalKey<NavigatorState>();

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await dotenv.load(fileName: ".env");

  final supabaseUrl    = dotenv.env['SUPABASE_URL'];
  final supabaseAnonKey = dotenv.env['SUPABASE_ANON_KEY'];
  if (supabaseUrl == null || supabaseAnonKey == null) {
    throw StateError('Missing SUPABASE_URL or SUPABASE_ANON_KEY');
  }
  await Supabase.initialize(url: supabaseUrl, anonKey: supabaseAnonKey);

  if (!kIsWeb) {
    // Set STRIPE_PUBLISHABLE_KEY in .env (pk_live_… for production builds).
    // The test key fallback is only suitable for TestFlight / internal testing.
    Stripe.publishableKey = dotenv.env['STRIPE_PUBLISHABLE_KEY'] ??
        "pk_test_51SW1114GlwNcKAYEd8fCjAcBf8rzZxRCCsdMW3pyrnSUceIIXlLpPbbp5n1mhQ7zVRM9nyNDjLbr56ElkYZ2YQNs00rZwbUIGV";
  }

  // Push notifications — no-op unless the FIREBASE_* keys are in .env.
  await PushService.instance.init(
    navigatorKey: rootNavigatorKey,
    onOpen: _openFromPush,
  );

  // Load saved language preference before building the widget tree
  final localeProvider = LocaleProvider();
  await localeProvider.loadSavedLocale();

  runApp(
    MultiProvider(
      providers: [
        ChangeNotifierProvider(create: (_) => CartProvider()),
        ChangeNotifierProvider.value(value: localeProvider),
      ],
      child: const MyApp(),
    ),
  );
}

/// Where a tapped push notification takes the user: booking-related
/// notifications open that booking's tracker, everything else the inbox.
Future<void> _openFromPush(Map<String, dynamic> data) async {
  final nav = rootNavigatorKey.currentState;
  if (nav == null) return;
  final type = '${data['type'] ?? ''}';
  final ref = '${data['reference_id'] ?? ''}';
  if (ref.isNotEmpty && (type.startsWith('booking') || type.contains('dispute'))) {
    try {
      final api = ApiService();
      final booking = await api.getBookingById(ref);
      final me = await api.getCurrentUserId();
      if (booking.isNotEmpty) {
        nav.push(MaterialPageRoute(
          builder: (_) => BookingTrackingScreen(
            booking: booking,
            isClient: booking['client_id'] == me,
          ),
        ));
        return;
      }
    } catch (_) {}
  }
  nav.push(MaterialPageRoute(builder: (_) => const NotificationsScreen()));
}

class MyApp extends StatelessWidget {
  const MyApp({super.key});

  @override
  Widget build(BuildContext context) {
    final locale = context.watch<LocaleProvider>().locale;

    return AuthRecoveryListener(
      navigatorKey: rootNavigatorKey,
      child: MaterialApp(
        title: 'LifeKit',
        debugShowCheckedModeBanner: false,
        navigatorKey: rootNavigatorKey,

        // ── Localisation ─────────────────────────────────────────────
        locale: locale,
        supportedLocales: LocaleProvider.supportedLocales,
        localizationsDelegates: const [
          AppLocalizations.delegate,
          GlobalMaterialLocalizations.delegate,
          GlobalWidgetsLocalizations.delegate,
          GlobalCupertinoLocalizations.delegate,
        ],
        // Auto-detect device locale on first launch; falls back to en
        localeResolutionCallback: (deviceLocale, supportedLocales) {
          if (deviceLocale == null) return const Locale('en');
          for (final supported in supportedLocales) {
            if (supported.languageCode == deviceLocale.languageCode) {
              return supported;
            }
          }
          return const Locale('en');
        },

        // ── Theme ─────────────────────────────────────────────────────
        theme: AppTheme.light(),

        home: const SplashScreen(),
        builder: (context, child) => GestureDetector(
          behavior: HitTestBehavior.opaque,
          onTap: () => FocusManager.instance.primaryFocus?.unfocus(),
          child: child,
        ),
      ),
    );
  }
}
